class SumWithoutPlusSign
{
    public static void main(String[] args) {
        //here we use concept of unary and binary operator 
        // unary operator means which deals with one operand (operand means data/variable/value)
        // example : -5 here ' - ' is a unary operator and 5 is operand
        // similarly binary operator means single operator 2 operands
        // now add 2 numbers without + operator 

        System.out.println(2- -3); // output 5 
        // first '-' is binary operator and second is unary which makes 3 as -3 
        // internally they both addup and acts like sum 

        // we have many types of operators we will see in future 
    }
}